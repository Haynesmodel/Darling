#!/usr/bin/env node
const fs = require('node:fs');
const path = require('node:path');
const standaloneCode = require('ajv/dist/standalone').default;
const esbuild = require('esbuild');
const { GENERATED_ASSETS } = require('./data/constants.cjs');
const { createAjv, schemaId } = require('./data/schema-validation.cjs');

function outputRootFromArgs(argv) {
  const index = argv.indexOf('--output-root');
  return index >= 0 ? path.resolve(argv[index + 1]) : process.cwd();
}

function specializeFormatRuntime(standaloneModule) {
  const specialized = standaloneModule.replaceAll(
    'require("ajv-formats/dist/formats")',
    'require("./scripts/data/standalone-formats.cjs")',
  );
  if (specialized.includes('ajv-formats/dist/formats')) {
    throw new Error('Generated validators still reference the full ajv-formats runtime');
  }
  return specialized;
}

function compactValidatorErrors(standaloneModule) {
  const compacted = standaloneModule.replace(
    /,schemaPath:"(?:\\.|[^"])*",keyword:"[^"]+",params:\{(?:"(?:\\.|[^"])*"|[^{}])*\}/g,
    '',
  );
  if (compacted.includes('schemaPath:') || compacted.includes('keyword:') || compacted.includes('params:')) {
    throw new Error('Generated validators contain an unsupported error-object shape');
  }
  return compacted;
}

function generateAssetValidators({ sourceRoot = process.cwd(), outputRoot = sourceRoot } = {}) {
  const ajv = createAjv(sourceRoot, {
    loopEnum: 0,
    loopRequired: 0,
    messages: false,
    code: { esm: true, source: true, optimize: 3 },
  });
  const ajvStandaloneModule = standaloneCode(ajv, {
    validateH2H: schemaId('h2h.schema.json'),
    validateSeasonSummary: schemaId('season-summary.schema.json'),
    validateRivalries: schemaId('rivalries.schema.json'),
    validateCurrentSeason: schemaId('current-season.schema.json'),
    validateDraftSpot: schemaId('draft-spot.schema.json'),
    validateDerivedStats: schemaId('derived-stats.schema.json'),
    validateAssetManifest: schemaId('asset-manifest.schema.json'),
  });
  const standaloneModule = specializeFormatRuntime(compactValidatorErrors(ajvStandaloneModule));
  const moduleCode = esbuild.buildSync({
    stdin: {
      contents: standaloneModule,
      loader: 'js',
      resolveDir: sourceRoot,
      sourcefile: 'asset-validator-runtime.mjs',
    },
    bundle: true,
    platform: 'browser',
    format: 'esm',
    target: 'es2022',
    write: false,
    legalComments: 'none',
  }).outputFiles[0].text;
  const wrappers = `

import type { AssetManifest, CurrentSeasonData, DerivedStats, DraftSpot, H2HGame, RivalryDefinition, SeasonSummaryRow } from './asset-types';

export function isH2H(value: unknown): value is H2HGame[] { return validateH2H(value) as boolean; }
export function isSeasonSummary(value: unknown): value is SeasonSummaryRow[] { return validateSeasonSummary(value) as boolean; }
export function isRivalries(value: unknown): value is RivalryDefinition[] { return validateRivalries(value) as boolean; }
export function isCurrentSeason(value: unknown): value is CurrentSeasonData { return validateCurrentSeason(value) as boolean; }
export function isDraftSpot(value: unknown): value is DraftSpot { return validateDraftSpot(value) as boolean; }
export function isDerivedStats(value: unknown): value is DerivedStats { return validateDerivedStats(value) as boolean; }
export function isAssetManifest(value: unknown): value is AssetManifest { return validateAssetManifest(value) as boolean; }
export type ValidatorName = 'H2H' | 'SeasonSummary' | 'Rivalries' | 'CurrentSeason' | 'DraftSpot' | 'DerivedStats' | 'AssetManifest';
export function getValidatorErrors(name: ValidatorName): Array<{ instancePath?: string; message?: string }> | null {
  const validators = { H2H: validateH2H, SeasonSummary: validateSeasonSummary, Rivalries: validateRivalries, CurrentSeason: validateCurrentSeason, DraftSpot: validateDraftSpot, DerivedStats: validateDerivedStats, AssetManifest: validateAssetManifest };
  return (validators[name] as any).errors || null;
}

export function formatValidatorErrors(assetPath: string, errors: Array<{ instancePath?: string; message?: string }> | null | undefined): string {
  const error = errors?.[0];
  if (!error) return \`\${assetPath}: schema validation failed\`;
  const location = error.instancePath ? error.instancePath.replace(/^\\//, '').replaceAll('/', '.') : 'root';
  return \`\${assetPath}: field "\${location}": \${error.message || 'schema validation failed'}\`;
}
`;
  const outputPath = path.join(outputRoot, GENERATED_ASSETS.AssetValidators.path);
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, `// This file is generated by scripts/generate_asset_validators.cjs. Do not edit manually.\n// @ts-nocheck\n${moduleCode.trim()}${wrappers}`);

  // LeagueLore is optional and must be safe to validate in the browser without
  // shipping the full AJV runtime. Keep this structural validator generated so
  // the loader and checked-in artifact cannot silently diverge.
  const loreOutputPath = path.join(outputRoot, 'src/data/generated/league-lore-validator.ts');
  const loreValidator = `
import type { LeagueLore } from './asset-types';
const O = (v: unknown): v is Record<string, any> => !!v && typeof v === 'object' && !Array.isArray(v);
const S = (v: unknown, max = 24000): v is string => typeof v === 'string' && v.length > 0 && v.length <= max;
const I = Number.isInteger;
const K = (v: any, allowed: string[]) => O(v) && Object.keys(v).every(key => allowed.includes(key));
const A = (v: unknown, p: (x: any) => boolean) => Array.isArray(v) && v.length > 0 && v.every(p);
const U = (v: any[], p: (x: any) => any) => new Set(v.map(p)).size === v.length;
const ID = (v: unknown) => S(v, 120) && /^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(v);
const OWN = (v: unknown) => S(v, 80);
const STRS = (v: unknown, max = 80) => A(v, x => S(x, max));
const YEAR = (v: any) => I(v) && v >= 1900 && v <= 2200;
const DATE = (v: any) => S(v, 40) && /^\\d{4}-\\d{2}-\\d{2}$/.test(v);
const ANCHOR = (v: unknown): boolean => {
  if (!O(v) || !S(v.type, 30)) return false;
  if (v.type === 'owner-season') return K(v, ['type','owner','season']) && OWN(v.owner) && YEAR(v.season);
  if (v.type === 'season') return K(v, ['type','season']) && YEAR(v.season);
  if (v.type === 'game') return K(v, ['type','season','week','game_type','owners']) && YEAR(v.season) && I(v.week) && v.week >= 0 && v.week <= 30 && S(v.game_type, 40) && Array.isArray(v.owners) && v.owners.length === 2 && v.owners.every(OWN);
  if (v.type === 'draft-slot') return K(v, ['type','season','owner','expected_slot']) && YEAR(v.season) && OWN(v.owner) && (v.expected_slot === undefined || I(v.expected_slot) && v.expected_slot > 0 && v.expected_slot <= 100);
  if (v.type === 'draft-selection') return K(v, ['type','season','owner','player_id']) && YEAR(v.season) && OWN(v.owner) && S(v.player_id, 120);
  if (v.type === 'transaction') return K(v, ['type','season','transaction_id']) && YEAR(v.season) && S(v.transaction_id, 160);
  if (v.type === 'record') return K(v, ['type','selector','game']) && v.selector === 'lowest-score' && ANCHOR(v.game);
  if (v.type === 'rivalry') return K(v, ['type','owners','slug']) && ((Array.isArray(v.owners) && v.owners.length === 2 && v.owners.every(OWN)) || S(v.slug, 120));
  return false;
};
const ENTRY = (v: unknown) => O(v) && K(v, ['id','category','title','teaser','body','season','occurred_year','completed_year','almanac_edition','owners','anchors','search_terms','provenance','sensitivity','enabled']) && ID(v.id) && S(v.category, 80) && S(v.title, 300) && S(v.teaser, 1000) && STRS(v.body, 24000) && Array.isArray(v.owners) && v.owners.every(OWN) && U(v.owners, x => x) && Array.isArray(v.anchors) && v.anchors.every(ANCHOR) && STRS(v.search_terms) && U(v.search_terms, x => x.toLowerCase()) && S(v.provenance, 1000) && [v.season, v.occurred_year, v.completed_year, v.almanac_edition].every(x => x === null || YEAR(x)) && ['ordinary', 'sensitive', 'respectful'].includes(v.sensitivity) && typeof v.enabled === 'boolean';
const MATCH = (v: any) => K(v, ['owner','season','owners','activation_value']) && (v.owner === undefined || OWN(v.owner)) && (v.season === undefined || YEAR(v.season)) && (v.activation_value === undefined || S(v.activation_value, 120)) && (v.owners === undefined || Array.isArray(v.owners) && v.owners.length === 2 && v.owners.every(OWN) && U(v.owners, x => x));
const SURFACES = ['global-search','draft-spot','history','curse-tracker','owner-hub','current-season','trophy','rivalry','dynasty','gauntlet','transactions','theme'];
const ACTIVATIONS = ['search','collection-open','selection','triple-activate','theme-sequence'];
const TRIGGER = (v: unknown) => O(v) && K(v, ['id','surface','activation','entry_id','collection_id','effect_id','once_policy','match','enabled']) && ID(v.id) && SURFACES.includes(v.surface) && ACTIVATIONS.includes(v.activation) && ['repeatable','scope','session'].includes(v.once_policy) && typeof v.enabled === 'boolean' && (('entry_id' in v) !== ('collection_id' in v)) && (!('entry_id' in v) || ID(v.entry_id)) && (!('collection_id' in v) || ID(v.collection_id)) && (!('effect_id' in v) || ID(v.effect_id)) && (!('match' in v) || MATCH(v.match));
const COLLECTION = (v: unknown) => O(v) && K(v, ['id','title','summary','entry_ids','search_terms','enabled']) && ID(v.id) && S(v.title, 300) && S(v.summary, 2000) && STRS(v.entry_ids) && U(v.entry_ids, x => x) && STRS(v.search_terms) && typeof v.enabled === 'boolean';
const EFFECT = (v: unknown) => O(v) && K(v, ['id','label','symbol','presentation','tone','duration_ms','motion_policy','enabled']) && ID(v.id) && S(v.label, 200) && S(v.symbol, 20) && ['overlay','rattle','cake','callout','static','dialog','confetti','bagel-shower','flies','suitcase','podium','snake-tail','chairs','crown','fog','target','ticket','blank-document'].includes(v.presentation) && ['playful','celebratory','respectful','informational'].includes(v.tone) && I(v.duration_ms) && v.duration_ms >= 0 && v.duration_ms <= 2500 && ['reduce-to-static','static'].includes(v.motion_policy) && typeof v.enabled === 'boolean';
export function isLeagueLore(value: unknown): value is LeagueLore {
  if (!O(value) || !K(value, ['schema_version','enabled','updated_at','source_policy','owners','commissioner_terms','collections','effects','entries','triggers']) || value.schema_version !== 1 || typeof value.enabled !== 'boolean' || !DATE(value.updated_at)) return false;
  if (!O(value.source_policy) || !K(value.source_policy, ['numeric_authority','almanac_narrative_through']) || !STRS(value.source_policy.numeric_authority) || !YEAR(value.source_policy.almanac_narrative_through)) return false;
  if (!A(value.owners, item => O(item) && K(item, ['owner','aliases']) && OWN(item.owner) && STRS(item.aliases) && U(item.aliases, x => x.toLowerCase())) || !U(value.owners, x => x.owner)) return false;
  if (!A(value.commissioner_terms, item => O(item) && K(item, ['id','owner','term_start','term_end','display_term','summary','entry_ids']) && ID(item.id) && OWN(item.owner) && YEAR(item.term_start) && (item.term_end === null || YEAR(item.term_end)) && S(item.display_term, 200) && S(item.summary, 2000) && STRS(item.entry_ids)) || !U(value.commissioner_terms, x => x.id)) return false;
  if (!A(value.collections, COLLECTION) || !U(value.collections, x => x.id) || !A(value.effects, EFFECT) || !U(value.effects, x => x.id) || !A(value.entries, ENTRY) || !U(value.entries, x => x.id) || !A(value.triggers, TRIGGER) || !U(value.triggers, x => x.id)) return false;
  return true;
}
`;
  fs.mkdirSync(path.dirname(loreOutputPath), { recursive: true });
  fs.writeFileSync(loreOutputPath, `// This file is generated by scripts/generate_asset_validators.cjs. Do not edit manually.\n// @ts-nocheck\n${loreValidator.trim()}\n`);

  const transactionStandaloneModule = specializeFormatRuntime(compactValidatorErrors(standaloneCode(ajv, {
    validateTransactionHistory: schemaId('transaction-history.schema.json'),
  })));
  const transactionModuleCode = esbuild.buildSync({
    stdin: {
      contents: transactionStandaloneModule,
      loader: 'js',
      resolveDir: sourceRoot,
      sourcefile: 'transaction-history-validator-runtime.mjs',
    },
    bundle: true,
    platform: 'browser',
    format: 'esm',
    target: 'es2022',
    write: false,
    legalComments: 'none',
  }).outputFiles[0].text;
  const transactionWrappers = `

import type { TransactionHistory } from './asset-types';

export function isTransactionHistory(value: unknown): value is TransactionHistory { return validateTransactionHistory(value) as boolean; }
export function getTransactionHistoryValidatorErrors(): Array<{ instancePath?: string; message?: string }> | null {
  return (validateTransactionHistory as any).errors || null;
}
`;
  const transactionOutputPath = path.join(outputRoot, GENERATED_ASSETS.TransactionHistoryValidator.path);
  fs.mkdirSync(path.dirname(transactionOutputPath), { recursive: true });
  fs.writeFileSync(
    transactionOutputPath,
    `// This file is generated by scripts/generate_asset_validators.cjs. Do not edit manually.\n// @ts-nocheck\n${transactionModuleCode.trim()}${transactionWrappers}`,
  );
  return outputPath;
}

if (require.main === module) {
  try {
    const output = generateAssetValidators({ outputRoot: outputRootFromArgs(process.argv.slice(2)) });
    console.log(`Generated ${path.relative(process.cwd(), output)}`);
  } catch (error) {
    console.error(error.message || error);
    process.exit(1);
  }
}

module.exports = {
  generateAssetValidators,
  compactValidatorErrors,
  outputRootFromArgs,
  specializeFormatRuntime,
};
